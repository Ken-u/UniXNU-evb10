#!/usr/bin/env python3
"""Kernel-step archive entry: turn the AP6398S firmware and nvram of .cache/firmware into kits/evb10/Evb10Wifi/wifi_fw.inc.

The files are vendor binaries and are neither committed nor embedded in any repository: put them in .cache/firmware with
scripts/extract-files.py first (SOURCE = vendor/rockchip/common/wifi/firmware of the Rockchip Android tree, --section "AP6398S Wi-Fi").
The generated include is ignored by git. Without the files the include holds empty arrays and the driver can still identify the module
(evb10-wifi=1); the download (evb10-wifi=2) then reports that no firmware is embedded.

.cache/firmware/join.txt (local, git-ignored) names the network the driver joins by itself once it is up; the text is embedded as kWifiJoin.

The firmware is written as it is. The nvram is written the way the chip wants it, which is what brcmfmac's brcmf_fw_nvram_strip makes of
the text file: comment lines and blank lines dropped, one "key=value" per line, each ended with a zero byte, one more zero byte at the
end, the whole padded to a multiple of 4 bytes, and a length token after it: the word count in the low half and its complement in the
high half, so that the firmware can check the block.
"""
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CACHE = ROOT / '.cache/firmware'
FIRMWARE = 'fw_bcm4359c0_ag.bin'
NVRAM = 'nvram_ap6398s.txt'
JOIN = CACHE / 'join.txt'   # optional: the SSID on the first line, the WPA2 passphrase (if any) on the second; never committed
OUT = ROOT / 'kits/evb10/Evb10Wifi/wifi_fw.inc'
MAX_NVRAM = 40000  # brcmfmac's BRCMF_FW_MAX_NVRAM_SIZE


def nvram_blob(text):
    entries = []
    for line in text[:MAX_NVRAM].splitlines():
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        entries.append(line.encode('ascii'))
    body = b''.join(entry + b'\0' for entry in entries)
    padded = -(-(len(body) + 1) // 4) * 4          # the extra zero byte, rounded up to a word
    body = body.ljust(padded, b'\0')
    words = padded // 4
    return body + struct.pack('<I', ((~words & 0xFFFF) << 16) | (words & 0xFFFF))


def array(name, data):
    # C++ has no zero-length arrays: an absent file is one zero byte with size 0.
    values = data if data else b'\0'
    rows = [', '.join(str(b) for b in values[i:i + 32]) for i in range(0, len(values), 32)]
    return f'static const unsigned char {name}[] = {{\n' + ',\n'.join(rows) + '\n};\n' + f'static const unsigned {name}Size = {len(data)};\n'


def main():
    firmware = (CACHE / FIRMWARE).read_bytes() if (CACHE / FIRMWARE).is_file() else b''
    nvram_path = CACHE / NVRAM
    nvram = nvram_blob(nvram_path.read_text(errors='replace')) if nvram_path.is_file() else b''
    if not firmware or not nvram:
        print(f'warning: {FIRMWARE} or {NVRAM} missing from {CACHE}: the Wi-Fi download will report no firmware '
              f'(scripts/extract-files.py SOURCE --section "AP6398S Wi-Fi")', file=sys.stderr)
    join = JOIN.read_bytes() if JOIN.is_file() else b''
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('// Generated by scripts/build-wifi-firmware.py: do not edit or commit.\n'
                   + array('kWifiFirmware', firmware) + array('kWifiNvram', nvram) + array('kWifiJoin', join))
    print(f'{OUT}: firmware {len(firmware)} bytes, nvram {len(nvram)} bytes, join file {len(join)} bytes')


main()
